function bindAudioEvents() {
  appState.audio.addEventListener('timeupdate', updateCurrentTrackFromAudio);
  appState.audio.addEventListener('loadedmetadata', updateCurrentTrackFromAudio);
  appState.audio.addEventListener('ended', () => {
    if (appState.repeat) {
      appState.audio.currentTime = 0;
      appState.audio.play();
      return;
    }
    const queue = appState.queue.length ? appState.queue : songs;
    const currentIndex = queue.findIndex((item) => item.id === appState.currentSongId);
    const nextIndex = appState.shuffle ? Math.floor(Math.random() * queue.length) : (currentIndex + 1) % queue.length;
    playQueueItem(queue[nextIndex], queue);
  });

  appState.audio.addEventListener('play', () => {
    appState.isPlaying = true;
    updateAudioStatus();
  });

  appState.audio.addEventListener('pause', () => {
    appState.isPlaying = false;
    updateAudioStatus();
  });

  appState.audio.addEventListener('error', () => {
    if (!appState.audio.currentSrc) return;
    const message = translations[appState.lang].audioError;
    window.alert(message);
  });
}

