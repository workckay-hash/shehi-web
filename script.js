function renderMiniPlayer() {
  const song = appState.currentSong || songs[0];
  const titleEl = document.getElementById('mini-title');
  const artistEl = document.getElementById('mini-artist');
  const coverEl = document.getElementById('mini-cover');
  const timeEl = document.getElementById('mini-time');
  const durationEl = document.getElementById('mini-duration');
  const progressEl = document.getElementById('mini-seek');
  const volumeEl = document.getElementById('mini-volume');

  if (!titleEl || !artistEl || !coverEl) return;
  titleEl.textContent = song.title;
  artistEl.textContent = song.artist;
  coverEl.src = song.cover;
  durationEl.textContent = Number.isFinite(appState.audio.duration) && appState.audio.duration > 0
    ? formatDuration(Math.round(appState.audio.duration))
    : song.duration || '0:00';
  const currentTime = formatDuration(Math.round(appState.audio.currentTime || 0));
  timeEl.textContent = currentTime;
  const ratio = Math.min(100, (appState.audio.currentTime / Math.max(appState.audio.duration || 1, 1)) * 100);
  if (progressEl && !progressEl.matches(':active')) {
    progressEl.value = String(ratio);
    progressEl.style.setProperty('--seek-progress', `${ratio}%`);
  }
  if (volumeEl) volumeEl.value = appState.audio.volume || 0.8;
}

