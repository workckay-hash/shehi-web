function setLanguage(lang) {
  const nextLanguage = Object.prototype.hasOwnProperty.call(translations, lang) ? lang : 'en';
  appState.lang = nextLanguage;
  localStorage.setItem('shehi-ui-language', nextLanguage);
  document.documentElement.lang = nextLanguage;
  document.documentElement.dir = nextLanguage === 'ar' ? 'rtl' : 'ltr';
  document.body.classList.toggle('rtl', nextLanguage === 'ar');
  document.querySelectorAll('.lang-option').forEach((button) => {
    button.classList.toggle('active', button.dataset.lang === nextLanguage);
  });
  applyTranslations();
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    if (translations[appState.lang][key]) {
      node.textContent = translations[appState.lang][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (translations[appState.lang][key]) {
      node.placeholder = translations[appState.lang][key];
    }
  });
}

